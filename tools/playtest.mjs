// Drives the Play mode headlessly (keys/mouse) and saves screenshots: node tools/playtest.mjs outdir
import { createRequire } from 'node:module';
import { startServer } from './serve.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const out = process.argv[2] || '.';
const server = await startServer(8767);
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 760 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://localhost:8767/index.html');
await page.waitForFunction('window.__done === true', null, { timeout: 90000 });
await page.mouse.move(640, 380);
await page.click('#modeplay');
await page.mouse.move(640, 380);
await page.evaluate(() => { window.__dbg.sim.camYaw = 0; window.__dbg.sim.camPitch = 0.12; });
await page.waitForTimeout(500);
const reset = () => page.evaluate(() => { window.__dbg.sim.camYaw = window.__dbg.sim.yaw; window.__dbg.sim.camPitch = 0.12; });
const snap = async (n) => page.screenshot({ path: `${out}/play_${n}.png` });
await page.keyboard.down('KeyW'); await page.waitForTimeout(1500); await snap('walk');
await page.keyboard.down('ShiftLeft'); await page.waitForTimeout(1500); await snap('run');
await page.keyboard.press('Space'); await page.waitForTimeout(700); await snap('jump');
await page.keyboard.up('ShiftLeft'); await page.keyboard.up('KeyW'); await page.waitForTimeout(1600);
await page.mouse.down({ button: 'right' }); await reset(); await page.waitForTimeout(800); await snap('ads');
await page.mouse.down({ button: 'left' }); await reset(); await page.waitForTimeout(260); await snap('adsfire');
await page.mouse.up({ button: 'left' });
await page.keyboard.down('KeyD'); await page.waitForTimeout(900); await snap('adsstrafe'); await page.keyboard.up('KeyD');
await page.mouse.up({ button: 'right' }); await page.waitForTimeout(600);
await page.keyboard.press('KeyH'); await page.waitForTimeout(600);
await page.mouse.down({ button: 'left' }); await reset(); await page.waitForTimeout(250); await snap('hipfire'); await page.mouse.up({ button: 'left' });
await page.mouse.up({ button: 'left' }); await page.keyboard.press('KeyH');
await page.keyboard.press('KeyC'); await page.waitForTimeout(900); await reset(); await snap('crouch');
await page.keyboard.down('KeyW'); await page.waitForTimeout(900); await snap('crouchwalk'); await page.keyboard.up('KeyW');
await page.keyboard.press('KeyZ'); await page.waitForTimeout(3200); await reset(); await snap('prone');
await page.keyboard.down('KeyW'); await page.waitForTimeout(1500); await snap('crawl'); await page.keyboard.up('KeyW');
await page.mouse.down({ button: 'left' }); await page.waitForTimeout(300); await snap('pronefire'); await page.mouse.up({ button: 'left' });
await page.keyboard.press('KeyZ'); await page.waitForTimeout(2600); await snap('standup');
console.log(await page.evaluate(() => { const d = window.__dbg.sim; return JSON.stringify({ posture: d.posture, base: d.base }); }));
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no page errors');
await browser.close(); server.close();
