// Re-solves the aiming cheek welds and writes src/calib-cache.js so pages load instantly.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { calibrate, CALIB_RESULTS, STANCES } from '../src/motion.js';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const t0 = Date.now();
calibrate();
const body = JSON.stringify(CALIB_RESULTS, null, 1);
fs.writeFileSync(path.join(root, 'src/calib-cache.js'), `// Generated by \`npm run calibrate\` (tools/calibrate.mjs). Safe to delete: stances are re-solved.\nexport const CALIB_CACHE = ${body};\n`);
for (const k of ['ads', 'crouchAds', 'prone']) console.log(k, 'cost', STANCES[k].calib.cost.toFixed(4));
console.log(`calibrated in ${Date.now() - t0} ms -> src/calib-cache.js`);
